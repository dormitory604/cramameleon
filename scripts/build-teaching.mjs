import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const prompts = {};
for (const name of ['router','style']) prompts[name] = (await readFile(new URL('prompts/'+name+'.md',root),'utf8')).replace(/\r\n/g,'\n');
const skills = {};
for (const name of ['concept','review','exam']) {
 const text = (await readFile(new URL('skills/'+name+'.md',root),'utf8')).replace(/\r\n/g,'\n');
 skills[name] = { name, version: createHash('sha256').update(text).digest('hex').slice(0,12), text };
}
const result = '// Generated by scripts/build-teaching.mjs; edit prompts/*.md and skills/*.md.\nexport const teachingContent = '+JSON.stringify({prompts,skills},null,2)+' as const;\n';
await writeFile(new URL('src/tools/teachingContent.generated.ts',root),result);
